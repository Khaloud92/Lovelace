/**
 * Represents a calendar entry as returned by the backend API.
 */
export interface CalendarEntry {
  id?: string;
  title: string;
  startDate: string;
  endDate?: string;
  location?: string;
  description?: string;
  color: string;
  isAutoGenerated?: boolean;

  /**
   * If set, this calendar entry was automatically created for a travel entry.
   * Deleting this entry will also delete the linked travel entry and its budget.
   */
  travelEntryId?: string;
}
