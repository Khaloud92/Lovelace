import { ComponentFixture, TestBed, fakeAsync, tick } from '@angular/core/testing';
import { CalendarComponent } from './calendar';
import { Calendar } from '../services/calendar';
import { HttpClientTestingModule } from '@angular/common/http/testing';
import { of, throwError } from 'rxjs';
import { CalendarEntry } from '../models/calendar-entry';
import { CalendarModule, DateAdapter } from 'angular-calendar';
import { adapterFactory } from 'angular-calendar/date-adapters/date-fns';
import { provideRouter } from '@angular/router';
import { provideLocationMocks } from '@angular/common/testing';
import { Component } from '@angular/core';
import { TravelEntryService } from '../travel-entry/travel-entry.service';
import { TravelEntry } from '../travel-entry/travel-entry.model';

@Component({ template: '', standalone: true })
class DummyComponent {}

const mockEntries: CalendarEntry[] = [
  {
    id: '1',
    title: 'Test Event',
    startDate: new Date('2026-05-26T10:00:00').toISOString(),
    endDate: new Date('2026-05-26T11:00:00').toISOString(),
    color: '#22d3ee',
    isAutoGenerated: false
  },
  {
    id: '2',
    title: 'Auto Event',
    startDate: new Date('2026-05-27T10:00:00').toISOString(),
    color: '#ff0000',
    isAutoGenerated: true
  }
];

const mockTrips: TravelEntry[] = [
  {
    id: 't1',
    title: 'Tokyo Trip',
    destination: 'Tokyo Japan',
    startDate: '2026-06-22',
    endDate: '2026-06-24',
    color: '#f59e0b',
    budget: {id: 'budget-1', name: 'Tokyo Budget', amount: 0 }
  },
  {
    id: 't2',
    title: 'Paris Trip',
    destination: 'Paris, France',
    startDate: '2026-06-23',
    endDate: '2026-06-26',
    color: '#10b981',
    budget: { id: 'budget-2' ,name: 'Paris Budget', amount: 0 }
  },
  {
    id: 't3',
    title: 'Berlin Trip',
    destination: 'Berlin',
    startDate: '2026-07-01',
    endDate: '2026-07-05',
    color: '#6366f1',
    budget: { id: 'budget-3', name: 'Berlin Budget', amount: 0 }
  }
];

describe('CalendarComponent', () => {
  let component: CalendarComponent;
  let fixture: ComponentFixture<CalendarComponent>;
  let calendarServiceSpy: jasmine.SpyObj<Calendar>;
  let travelEntryServiceSpy: jasmine.SpyObj<TravelEntryService>;

  beforeEach(async () => {
    calendarServiceSpy = jasmine.createSpyObj('Calendar', [
      'getAllEntries', 'deleteEntry', 'addEntry', 'updateEntry'
    ]);
    calendarServiceSpy.getAllEntries.and.returnValue(of(mockEntries));

    travelEntryServiceSpy = jasmine.createSpyObj('TravelEntryService', [
      'getTravelEntries', 'updateTravelEntry', 'triggerRefresh'
    ]);
    travelEntryServiceSpy.getTravelEntries.and.returnValue(of(mockTrips));
    travelEntryServiceSpy.triggerRefresh.and.returnValue();

    await TestBed.configureTestingModule({
      imports: [
        CalendarComponent,
        HttpClientTestingModule,
        CalendarModule.forRoot({ provide: DateAdapter, useFactory: adapterFactory })
      ],
      providers: [
        { provide: Calendar, useValue: calendarServiceSpy },
        { provide: TravelEntryService, useValue: travelEntryServiceSpy },
        provideRouter([{ path: 'calendar', component: DummyComponent }]),
        provideLocationMocks()
      ]
    }).compileComponents();

    fixture = TestBed.createComponent(CalendarComponent);
    component = fixture.componentInstance;
    fixture.detectChanges();
  });

  it('should create', () => {
    expect(component).toBeTruthy();
  });

  it('should load calendar entries on init', () => {
    expect(calendarServiceSpy.getAllEntries).toHaveBeenCalled();
    expect(component.events.length).toBe(2);
    expect(component.events[0].title).toBe('Test Event');
  });

  it('should map backend entries to CalendarEvent format', () => {
    const firstEvent = component.events[0];
    expect(firstEvent.id).toBe('1');
    expect(firstEvent.color?.primary).toBe('#22d3ee');
    expect(firstEvent.start).toEqual(new Date('2026-05-26T10:00:00'));
  });

  it('should call deleteEntry when deleteSelectedEntry is called', fakeAsync(() => {
    calendarServiceSpy.deleteEntry.and.returnValue(of(undefined));
    spyOn(window, 'confirm').and.returnValue(true);
    component.selectedEntryId = '1';
    component.isEditMode = true;
    component.isModalOpen = true;
    component.deleteSelectedEntry();
    tick(200);
    expect(calendarServiceSpy.deleteEntry).toHaveBeenCalledWith('1');
    expect(component.isModalOpen).toBeFalse();
  }));

  it('should not call deleteEntry when user cancels', () => {
    spyOn(window, 'confirm').and.returnValue(false);
    component.selectedEntryId = '1';
    component.deleteSelectedEntry();
    expect(calendarServiceSpy.deleteEntry).not.toHaveBeenCalled();
  });

  it('should handle delete error gracefully', fakeAsync(() => {
    calendarServiceSpy.deleteEntry.and.returnValue(throwError(() => new Error('Delete failed')));
    spyOn(window, 'confirm').and.returnValue(true);
    spyOn(console, 'error');
    component.selectedEntryId = '1';
    component.deleteSelectedEntry();
    tick();
    expect(console.error).toHaveBeenCalled();
    expect(component.isSaving).toBeFalse();
  }));

  it('should open edit modal with entry data', () => {
    component.rawEntries = mockEntries;
    component.openEditModal('1');
    expect(component.isModalOpen).toBeTrue();
    expect(component.isEditMode).toBeTrue();
    expect(component.selectedEntryId).toBe('1');
    expect(component.newAppointment.title).toBe('Test Event');
  });

  it('should not open edit modal for auto-generated entries', () => {
    spyOn(window, 'alert');
    component.rawEntries = mockEntries;
    component.openEditModal('2');
    expect(component.isModalOpen).toBeFalse();
    expect(window.alert).toHaveBeenCalledWith(
      'Automatically created entries cannot be edited or deleted.'
    );
  });

  it('should open modal in create mode and reset form', () => {
    component.isEditMode = true;
    component.newAppointment = { title: 'Old' };
    component.openModal();
    expect(component.isModalOpen).toBeTrue();
    expect(component.isEditMode).toBeFalse();
    expect(component.newAppointment).toEqual({});
    expect(component.selectedColor).toBe('#22d3ee');
  });

  it('should close modal and reset form state', () => {
    component.isModalOpen = true;
    component.isSaving = true;
    component.newAppointment = { title: 'Something' };
    component.closeModal();
    expect(component.isModalOpen).toBeFalse();
    expect(component.isSaving).toBeFalse();
    expect(component.newAppointment).toEqual({});
  });

  it('should change view to week', () => {
    component.setView('week');
    expect(component.view).toBe('week');
  });

  it('should expose a week event template', () => {
    expect(component.weekEventTemplate).toBeTruthy();
  });

  it('should call addEntry when saving a new entry', fakeAsync(() => {
    calendarServiceSpy.addEntry.and.returnValue(of({
      id: '3',
      title: 'New Event',
      startDate: new Date('2026-06-01T10:00:00').toISOString(),
      isAutoGenerated: false,
      color: '#22d3ee'
    }));
    component.isEditMode = false;
    component.isFullTrip = false;
    component.newAppointment = { title: 'New Event', startDate: '2026-06-01T10:00' };
    component.selectedColor = '#22d3ee';
    component.saveEntry();
    tick(200);
    expect(calendarServiceSpy.addEntry).toHaveBeenCalled();
    expect(component.isModalOpen).toBeFalse();
  }));

  it('should not call addEntry if title is missing', () => {
    spyOn(window, 'alert');
    component.isEditMode = false;
    component.newAppointment = { startDate: '2026-06-01T10:00' };
    component.saveEntry();
    expect(calendarServiceSpy.addEntry).not.toHaveBeenCalled();
  });

  it('should call updateEntry when saving an existing entry', fakeAsync(() => {
    calendarServiceSpy.updateEntry.and.returnValue(of({
      id: '1',
      title: 'Updated Event',
      startDate: new Date('2026-05-26T10:00:00').toISOString(),
      isAutoGenerated: false,
      color: '#22d3ee'
    }));
    component.isEditMode = true;
    component.selectedEntryId = '1';
    component.newAppointment = { title: 'Updated Event', startDate: '2026-05-26T10:00' };
    component.selectedColor = '#22d3ee';
    component.saveEntry();
    tick(200);
    expect(calendarServiceSpy.updateEntry).toHaveBeenCalledWith('1', jasmine.any(Object));
    expect(component.isModalOpen).toBeFalse();
  }));

  describe('updateHeaderImages', () => {
    it('should only show trips of the current month', () => {
      component.viewDate = new Date('2026-06-01');
      component['allTrips'] = mockTrips;
      component['updateHeaderImages']();
      expect(component.headerImages.length).toBe(2);
      expect(component.headerImages.find(i => i.destination === 'Berlin')).toBeUndefined();
    });

    it('should set hasTripsThisMonth to false when no trips in month', () => {
      component.viewDate = new Date('2026-09-01');
      component['allTrips'] = mockTrips;
      component['updateHeaderImages']();
      expect(component.hasTripsThisMonth).toBeFalse();
      expect(component.headerImages.length).toBe(0);
    });

    it('should parse destination with space separator correctly', () => {
      component.viewDate = new Date('2026-06-01');
      component['allTrips'] = mockTrips;
      component['updateHeaderImages']();
      const tokyo = component.headerImages.find(i => i.destination === 'Tokyo');
      expect(tokyo).toBeDefined();
      expect(tokyo?.country).toBe('Japan');
    });

    it('should parse destination with comma separator correctly', () => {
      component.viewDate = new Date('2026-06-01');
      component['allTrips'] = mockTrips;
      component['updateHeaderImages']();
      const paris = component.headerImages.find(i => i.destination === 'Paris');
      expect(paris).toBeDefined();
      expect(paris?.country).toBe('France');
    });

    it('should use trip color as accentColor', () => {
      component.viewDate = new Date('2026-06-01');
      component['allTrips'] = mockTrips;
      component['updateHeaderImages']();
      const tokyo = component.headerImages.find(i => i.destination === 'Tokyo');
      expect(tokyo?.accentColor).toBe('#f59e0b');
    });

    it('should fall back to default color if trip has no color', () => {
      const tripWithoutColor: TravelEntry = {
        id: 't4',
        title: 'Test',
        destination: 'Rome Italy',
        startDate: '2026-06-10',
        endDate: '2026-06-12',
        budget: { id: 'budget-4' ,name: 'Rome Budget', amount: 0 }
      };
      component.viewDate = new Date('2026-06-01');
      component['allTrips'] = [tripWithoutColor];
      component['updateHeaderImages']();
      expect(component.headerImages[0].accentColor).toBe('#10b981');
    });
  });

  describe('getImageUrl cache', () => {
    it('should return the same URL for the same destination', () => {
      const url1 = component['getImageUrl']('Tokyo Japan');
      const url2 = component['getImageUrl']('Tokyo Japan');
      expect(url1).toBe(url2);
    });

    it('should return different URLs for different destinations', () => {
      const url1 = component['getImageUrl']('Tokyo Japan');
      const url2 = component['getImageUrl']('Paris France');
      expect(url1).not.toBe(url2);
    });
  });
});
