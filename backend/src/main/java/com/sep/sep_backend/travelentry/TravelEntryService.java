package com.sep.sep_backend.travelentry;

import com.sep.sep_backend.budget.Budget;
import com.sep.sep_backend.budget.BudgetService;
import com.sep.sep_backend.budget.dto.response.BudgetResponse;
import com.sep.sep_backend.calendar.CalendarEntry;
import com.sep.sep_backend.calendar.CalendarEntryRepository;
import com.sep.sep_backend.travelentry.dto.CreateTravelEntryrequest;
import com.sep.sep_backend.travelentry.dto.TravelEntryResponse;
import jakarta.transaction.Transactional;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.time.ZoneOffset;
import java.util.List;
import java.util.UUID;

/**
 * Business logic for travel entries. All reads and writes are scoped to the owning user.
 */
@Service
@RequiredArgsConstructor
@Transactional
public class TravelEntryService {

    private final TravelEntryRepository repository;
    private final BudgetService budgetService;
    private final CalendarEntryRepository calendarEntryRepository;

    /**
     * Returns all travel entries of the given user.
     *
     * @param userId id of the user
     * @return the user's travel entries
     */
    public List<TravelEntryResponse> findAll(String userId) {
        return repository.findByUserId(userId).stream()
                .map(this::toResponse)
                .toList();
    }

    /**
     * Creates a travel entry together with a matching calendar entry and optional budget.
     *
     * @param request the trip data
     * @return the created entry
     */
    public TravelEntryResponse create(CreateTravelEntryrequest request) {
        validateTravelCreation(request);

        String tripColor = (request.getColor() != null && !request.getColor().isBlank())
                ? request.getColor()
                : "#10b981";

        TravelEntry travelEntry = new TravelEntry();
        travelEntry.setTitle(request.getTitle());
        travelEntry.setDestination(request.getDestination());
        travelEntry.setStartDate(request.getStartDate());
        travelEntry.setEndDate(request.getEndDate());
        travelEntry.setDescription(request.getDescription());
        travelEntry.setUserId(request.getUserId());
        travelEntry.setColor(tripColor);

        CalendarEntry calendarEntry = new CalendarEntry();
        calendarEntry.setTitle(request.getTitle());
        calendarEntry.setStartDate(request.getStartDate().atStartOfDay(ZoneOffset.UTC));
        calendarEntry.setEndDate(request.getEndDate().atTime(23, 59, 59).atZone(ZoneOffset.UTC));
        calendarEntry.setLocation(request.getDestination());
        calendarEntry.setDescription(request.getDescription());
        calendarEntry.setColor(tripColor);
        calendarEntry.setUserId(request.getUserId());
        calendarEntry.setTravelEntry(travelEntry);
        calendarEntry.setAutoGenerated(true);
        travelEntry.getCalendarEntries().add(calendarEntry);

        TravelEntry savedEntry = repository.save(travelEntry);

        if (request.getBudget() != null) {
            budgetService.create(savedEntry.getId(), request.getBudget());
        }

        return toResponse(savedEntry);
    }

    /**
     * Updates a travel entry if it belongs to the given user.
     *
     * @param id           id of the entry
     * @param updatedEntry the new values
     * @param userId       id of the requesting user
     * @return the updated entry
     */
    public TravelEntryResponse update(UUID id, TravelEntry updatedEntry, String userId) {
        validateTravelEntry(updatedEntry);

        TravelEntry existingEntry = repository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Travel entry not found: " + id));

        if (!userId.equals(existingEntry.getUserId())) {
            throw new IllegalArgumentException("Travel entry not found: " + id);
        }

        existingEntry.setTitle(updatedEntry.getTitle());
        existingEntry.setDestination(updatedEntry.getDestination());
        existingEntry.setStartDate(updatedEntry.getStartDate());
        existingEntry.setEndDate(updatedEntry.getEndDate());
        existingEntry.setDescription(updatedEntry.getDescription());

        if (updatedEntry.getColor() != null && !updatedEntry.getColor().isBlank()) {
            existingEntry.setColor(updatedEntry.getColor());
        }

        Budget incomingBudget = updatedEntry.getBudget();
        if (incomingBudget != null) {
            if (existingEntry.getBudget() != null) {
                existingEntry.getBudget().setAmount(incomingBudget.getAmount());
                existingEntry.getBudget().setName(incomingBudget.getName());
            } else {
                incomingBudget.setTravelEntry(existingEntry);
                existingEntry.setBudget(incomingBudget);
            }
        }

        return toResponse(repository.save(existingEntry));
    }

    /**
     * Deletes a travel entry if it belongs to the given user.
     *
     * @param id     id of the entry
     * @param userId id of the requesting user
     */
    public void delete(UUID id, String userId) {
        TravelEntry entry = repository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Travel entry not found: " + id));

        if (!userId.equals(entry.getUserId())) {
            throw new IllegalArgumentException("Travel entry not found: " + id);
        }

        repository.deleteById(id);
    }

    private TravelEntryResponse toResponse(TravelEntry entry) {
        BudgetResponse budgetResponse = null;
        if (entry.getBudget() != null) {
            budgetResponse = new BudgetResponse(
                    entry.getBudget().getId(),
                    entry.getBudget().getName(),
                    entry.getBudget().getAmount()
            );
        }

        return new TravelEntryResponse(
                entry.getId(),
                entry.getTitle(),
                entry.getDestination(),
                entry.getStartDate(),
                entry.getEndDate(),
                entry.getDescription(),
                entry.getUserId(),
                entry.getColor(),
                budgetResponse
        );
    }

    private void validateTravelCreation(CreateTravelEntryrequest request) {
        if (request.getEndDate().isBefore(request.getStartDate())) {
            throw new IllegalArgumentException("End date must be after start date");
        }
    }

    private void validateTravelEntry(TravelEntry travelEntry) {
        if (travelEntry.getTitle() == null || travelEntry.getTitle().isBlank()) {
            throw new IllegalArgumentException("Title is required");
        }
        if (travelEntry.getDestination() == null || travelEntry.getDestination().isBlank()) {
            throw new IllegalArgumentException("Destination is required");
        }
        if (travelEntry.getStartDate() == null || travelEntry.getEndDate() == null) {
            throw new IllegalArgumentException("Start date and end date are required");
        }
        if (travelEntry.getEndDate().isBefore(travelEntry.getStartDate())) {
            throw new IllegalArgumentException("End date must be after start date");
        }
    }
}