package com.sep.sep_backend.calendar;

import com.sep.sep_backend.calendar.dto.CalendarEntryResponse;
import com.sep.sep_backend.calendar.dto.CreateCalendarEntryRequest;
import com.sep.sep_backend.calendar.dto.UpdateCalendarEntryRequest;
import com.sep.sep_backend.travelentry.TravelEntry;
import com.sep.sep_backend.travelentry.TravelEntryRepository;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.UUID;

/**
 * Service for managing calendar entries.
 */
@Service
public class CalendarEntryService {

    private final CalendarEntryRepository repository;
    private final TravelEntryRepository travelEntryRepository;

    public CalendarEntryService(
            CalendarEntryRepository repository,
            TravelEntryRepository travelEntryRepository) {
        this.repository = repository;
        this.travelEntryRepository = travelEntryRepository;
    }

    /**
     * Returns all calendar entries as response DTOs.
     */
    public List<CalendarEntryResponse> getAllEntries(String userId) {
        return repository.findByUserId(userId)
                .stream()
                .map(this::toResponse)
                .toList();
    }

    /**
     * Creates and stores a new calendar entry.
     * If a travelEntryId is provided, the entry will be linked to that trip,
     * but it is always treated as a manually created entry.
     *
     * @throws IllegalArgumentException if the end date is before the start date
     * @throws IllegalArgumentException if the referenced travel entry does not exist
     */
    public CalendarEntryResponse createEntry(CreateCalendarEntryRequest request, String userId) {
        if (request.getEndDate() != null && request.getEndDate().isBefore(request.getStartDate())) {
            throw new IllegalArgumentException("End date must not be before start date.");
        }

        CalendarEntry entry = new CalendarEntry();
        entry.setTitle(request.getTitle().trim());
        entry.setStartDate(request.getStartDate());
        entry.setEndDate(request.getEndDate());
        entry.setLocation(request.getLocation());
        entry.setDescription(request.getDescription());
        entry.setColor(request.getColor());
        entry.setUserId(userId);
        entry.setAutoGenerated(false);

        if (request.getTravelEntryId() != null) {
            TravelEntry travelEntry = travelEntryRepository.findById(request.getTravelEntryId())
                    .orElseThrow(() -> new IllegalArgumentException("Travel entry not found."));
            entry.setTravelEntry(travelEntry);
        }

        return toResponse(repository.save(entry));
    }

    /**
     * Updates an existing calendar entry.
     */
    public CalendarEntryResponse updateEntry(UUID id, UpdateCalendarEntryRequest request) {
        CalendarEntry entry = repository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Calendar entry not found."));

        if (request.getEndDate() != null && request.getEndDate().isBefore(request.getStartDate())) {
            throw new IllegalArgumentException("End date must not be before start date.");
        }

        entry.setTitle(request.getTitle().trim());
        entry.setStartDate(request.getStartDate());
        entry.setEndDate(request.getEndDate());
        entry.setLocation(request.getLocation());
        entry.setDescription(request.getDescription());
        entry.setColor(request.getColor());

        return toResponse(repository.save(entry));
    }

    /**
     * Deletes an existing calendar entry.
     * If the entry is the auto-generated trip entry, the whole travel entry
     * (and its budget, via cascade) is deleted. Manually created entries
     * are deleted on their own, even if linked to a travel entry.
     *
     * @throws IllegalArgumentException if no calendar entry with the given id exists
     */
    public void deleteEntry(UUID id) {
        CalendarEntry entry = repository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Calendar entry not found."));

        if (entry.isAutoGenerated() && entry.getTravelEntry() != null) {
            travelEntryRepository.deleteById(entry.getTravelEntry().getId());
        } else {
            repository.delete(entry);
        }
    }

    /**
     * Maps a CalendarEntry entity to a CalendarEntryResponse DTO.
     */
    private CalendarEntryResponse toResponse(CalendarEntry entry) {
        return new CalendarEntryResponse(
                entry.getId(),
                entry.getTitle(),
                entry.getStartDate(),
                entry.getEndDate(),
                entry.getLocation(),
                entry.getDescription(),
                entry.getColor(),
                entry.getTravelEntry() != null ? entry.getTravelEntry().getId() : null
        );
    }
}