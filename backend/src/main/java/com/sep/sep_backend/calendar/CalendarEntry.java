package com.sep.sep_backend.calendar;

import com.sep.sep_backend.travelentry.TravelEntry;
import jakarta.persistence.*;
import java.time.ZonedDateTime;
import java.util.UUID;

/**
 * Represents a calendar entry.
 * A calendar entry has a required title and start date.
 * End date, location, and description are optional.
 */
@Entity
@Table(name = "calendar_entries")
public class CalendarEntry {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false)
    private String title;

    @Column(nullable = false)
    private ZonedDateTime startDate;

    private ZonedDateTime endDate;

    private String location;

    @Column(length = 2000)
    private String description;

    @Column(nullable = false, length = 7)
    private String color;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "travel_entry_id", nullable = true)
    private TravelEntry travelEntry;

    private String userId;

    /**
     * True only for the single entry that was automatically created
     * to represent the trip itself in the calendar.
     * False for all manually created events, even if they are linked
     * to a travel entry via travelEntry.
     */
    @Column(nullable = false)
    private boolean isAutoGenerated = false;

    public UUID getId() { return id; }
    public void setId(UUID id) { this.id = id; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public ZonedDateTime getStartDate() { return startDate; }
    public void setStartDate(ZonedDateTime startDate) { this.startDate = startDate; }

    public ZonedDateTime getEndDate() { return endDate; }
    public void setEndDate(ZonedDateTime endDate) { this.endDate = endDate; }

    public String getLocation() { return location; }
    public void setLocation(String location) { this.location = location; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public String getColor() { return color; }
    public void setColor(String color) { this.color = color; }

    public TravelEntry getTravelEntry() { return travelEntry; }
    public void setTravelEntry(TravelEntry travelEntry) { this.travelEntry = travelEntry; }

    public String getUserId() { return userId; }
    public void setUserId(String userId) { this.userId = userId; }

    public boolean isAutoGenerated() { return isAutoGenerated; }
    public void setAutoGenerated(boolean autoGenerated) { this.isAutoGenerated = autoGenerated; }
}